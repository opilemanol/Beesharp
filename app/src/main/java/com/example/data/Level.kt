    fun getLevel(id: Int): Level {
        if (levels.isEmpty()) {
            return Level(id, "BEE", 3, "A busy pollinating insect")
        }
        val index = (id - 1) % levels.size
        val baseLevel = levels[index]
        return Level(
            levelId = id,
            wordToSpell = baseLevel.wordToSpell,
            hintCount = baseLevel.hintCount,
            hintContext = baseLevel.hintContext
        )
    }
